object ZaslonLanguageStore {
    private const val PREFS_NAME = "zaslon_prefs"
    private const val KEY_UI_LANG = "ui_lang"

    @Volatile
    var current: ZaslonLanguage = ZaslonLanguage.TR
        private set

    fun init(context: Context): ZaslonLanguage {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val loaded = ZaslonLanguage.fromCode(prefs.getString(KEY_UI_LANG, ZaslonLanguage.TR.code))
        current = loaded
        return loaded
    }

    fun setLanguage(context: Context, language: ZaslonLanguage) {
        current = language
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_UI_LANG, language.code)
            .apply()
    }

    fun strings(language: ZaslonLanguage = current): ZaslonStrings = when (language) {
        ZaslonLanguage.TR -> TR_STRINGS
        ZaslonLanguage.EN -> EN_STRINGS
        ZaslonLanguage.RU -> RU_STRINGS
        ZaslonLanguage.DE -> DE_STRINGS
