    val code: String,
    val nativeLabel: String,
    val shortCode: String
) {
    TR("tr", "Türkçe", "TR"),
    EN("en", "English", "EN"),
    RU("ru", "Русский", "RU"),
    DE("de", "Deutsch", "DE");

    companion object {
        fun fromCode(raw: String?): ZaslonLanguage {
            val norm = raw?.trim()?.lowercase()?.take(2)
            return entries.firstOrNull { it.code == norm } ?: TR
        }
    }
}

